## WebSIL: a web page for browsing a library - see BUILDWEB in
## docs/parameters.md
##
## The page reads its data from JavaScript files rather than JSON, as
## browsers refuse fetch() of file:// URLs but do run <script src>.
##   web/imageData.js - every image and tag; rebuilt only by BUILDWEB
##   web/silStamp.js  - when sil last changed the library, when the data
##                      was last built, and the GITWEB setting; rewritten
##                      by runs that change the library (see
##                      stampChangedLibraries), so the page can tell when
##                      its data is out of date

srcLib "index"
srcLib "tags"

## Page files copied from templates/web on each BUILDWEB, so a library
## picks up page changes from SIL updates: template name -> library path
declare -gA _silWebFiles=(
    [WebSIL.html]=WebSIL.html
    [websil.js]=web/websil.js
    [websil.css]=web/websil.css
)

## Lines in a library's .gitignore keeping the page out of git, unless GITWEB
declare -ga _silWebIgnores=("/web/" "/WebSIL.html")

#######################################
# Escape text for use inside a JSON string. Control characters, which
# can only arrive in a command line, become spaces.
# Arguments:
#   $1 - Text
# Outputs:
#   Escaped text, without quotes, to STDOUT
#######################################
function jsonEscape {
    local s="$1"
    s="${s//\\/\\\\}"
    s="${s//\"/\\\"}"
    s="${s//[[:cntrl:]]/ }"
    printf '%s' "$s"
}

#######################################
# Decide whether the web page is shared through git (GITWEB): as given
# for this run, otherwise as recorded in web/silStamp.js, otherwise not.
# Globals:
#   SIL_LIBRARY, SIL_GITWEB
# Outputs:
#   'true' or 'false' to STDOUT, as a JavaScript boolean
#######################################
function webGitSetting {
    if [[ -n "${SIL_GITWEB:-}" ]]; then
        flagIsSet GITWEB && echo true || echo false
    elif grep -q '"gitweb":true' -- "$SIL_LIBRARY/web/silStamp.js" 2> /dev/null; then
        echo true
    else
        echo false
    fi
}

#######################################
# Write web/silStamp.js, recording when sil last changed the library, the
# command that did, when the page data was built, and the GITWEB setting.
# Only for libraries with a web page. One value to a line, for people
# reading or grepping it.
# Globals:
#   SIL_LIBRARY, _silCommandLine
# Arguments:
#   $1 - Optional epoch seconds of the change; otherwise the change time
#        and command are kept from the existing stamp (eg to record GITWEB)
#   $2 - Optional epoch seconds the page data was built; otherwise kept
#        from the existing stamp
# Returns:
#   0 on success or with no web page; 1 if the stamp can't be written
#######################################
function webStamp {
    local web="$SIL_LIBRARY/web" now="${1:-}" built="${2:-}" command tmp
    [[ -d "$web" ]] || return 0
    command="${_silCommandLine:-sil}"
    if [[ -z "$built" ]]; then
        built="$(grep -o '"built":[0-9]*' -- "$web/silStamp.js" 2> /dev/null)"
        built="${built#*:}"
    fi
    if [[ -z "$now" ]]; then
        now="$(grep -o '"changed":[0-9]*' -- "$web/silStamp.js" 2> /dev/null)"
        now="${now#*:}"
        ## The stamp is JSON escaped already, and SIL's own command lines
        ## have no newlines, so the line is taken as it stands
        command="$(sed -n 's/^  "command":"\(.*\)",$/\1/p' -- "$web/silStamp.js" 2> /dev/null)"
        command="${command:-sil}"
    else
        command="$(jsonEscape "$command")"
    fi
    now="${now:-0}"
    tmp="$(silMktemp)" || return 1
    {
        printf '%s\n' \
            '/*' \
            ' * WebSIL stamp: when sil last used this library, and when the page' \
            ' * data (imageData.js) was built, so WebSIL.html can say when its data' \
            ' * is out of date. Also records GITWEB, whether web/ and WebSIL.html' \
            ' * are shared through git.' \
            ' *' \
            ' * Generated by sil, and rewritten by runs that change the library:' \
            ' * do not edit. Change' \
            ' * GITWEB with: sil GITWEB=on BUILDWEB (or off)' \
            ' */' \
            'window.SIL_STAMP = {'
        printf '  "changed":%s,\n  "changedText":"%s",\n  "command":"%s",\n  "built":%s,\n  "gitweb":%s\n};\n' \
            "$now" "$(date -d "@$now" '+%Y-%m-%d %H:%M:%S')" \
            "$command" "${built:-0}" "$(webGitSetting)"
    } > "$tmp" && placeLibraryFile "$tmp" "$web/silStamp.js"
}

#######################################
# Test whether this run changed what a library's web page shows: images
# stored or removed, and tag folders or links made or removed. Each of
# these adds or removes a folder entry, which updates the folder's time,
# so only folders are compared, not every link. The fingerprint index
# and sources list, in images/ itself, are not shown, so are skipped.
# Changes made before this run's BUILDWEB are already in its data.
# Arguments:
#   $1 - Absolute library path
#   $2 - Start marker made when the run locked it (markLibraryStart)
# Returns:
#   0 if changed since the marker (or the build, if later), 1 otherwise
#######################################
function libraryChangedSince {
    local lib="$1" ref="$2"
    [[ "$lib/web/imageData.js" -nt "$ref" ]] && ref="$lib/web/imageData.js"
    [[ -n "$({ find "$lib/tags" -type d -newer "$ref" -print -quit
        find "$lib/images" -mindepth 1 -type d -newer "$ref" -print -quit
        } 2> /dev/null)" ]]
}

#######################################
# At exit, update the web page stamp (webStamp) of each library this run
# changed (libraryChangedSince), so an open page offers a BUILDWEB only when
# its data is out of date, then remove the start markers. Libraries the
# run only read, such as a COPY source, are left alone. Set as an EXIT
# trap by sil.sh.
# Globals:
#   _silLibraryStart; SIL_LIBRARY and SIL_GITWEB are masked, so each
#   library keeps its recorded GITWEB
#######################################
function stampChangedLibraries {
    local SIL_LIBRARY SIL_GITWEB="" marker
    for SIL_LIBRARY in "${!_silLibraryStart[@]}"; do
        marker="${_silLibraryStart[$SIL_LIBRARY]}"
        if libraryChangedSince "$SIL_LIBRARY" "$marker"; then
            webStamp "$(date +%s)" || msgWarn "[!] Could not update $SIL_LIBRARY/web/silStamp.js"
        fi
        rm -f -- "$marker"
    done
}

#######################################
# List the facts the page needs, as tab separated records in the order
# webDataJs reads them:
#   D <tag path>                  - every tag folder, except the date tag
#   A <alias path> <target path>  - LINK aliases
#   L <folder> <image file name>  - every tag link, date tag included
#   I <image file name> <bytes>   - every stored image
# Tag folders reached only through an alias are not listed twice. Tag
# paths are escaped for JSON strings: SIL allows neither '"' nor '\' in
# tags, but folders made by hand or by older versions may have them.
# Globals:
#   SIL_LIBRARY, _silDateTag
# Outputs:
#   Records to STDOUT
#######################################
function webFacts {
    local tags="$SIL_LIBRARY/tags" alias target
    (
        cd -- "$tags" || exit 1
        find . -mindepth 1 -type d ! -path "./$_silDateTag" ! -path "./$_silDateTag/*" \
            -printf 'D\t%P\n' | LC_ALL=C sort
        find . -type l -xtype d ! -path "./$_silDateTag/*" -printf '%P\n' | LC_ALL=C sort \
            | while IFS= read -r alias; do
                target="$(realpath --relative-to=. -- "$alias" 2> /dev/null)" || continue
                printf 'A\t%s\t%s\n' "$alias" "$target"
            done
        find . -type l -xtype f -printf 'L\t%h\t%f\n' | LC_ALL=C sort
    ) | sed 's/\\/\\\\/g; s/"/\\"/g'
    find "$SIL_LIBRARY/images" -mindepth 2 -maxdepth 2 -type f -printf 'I\t%f\t%s\n' \
        | LC_ALL=C sort
}

#######################################
# Turn webFacts records into the page's data file. Each image becomes
# [hash, suffix, bytes, date added or null, [tag numbers]], the numbers
# indexing the tags list, to keep the file small for large libraries.
# Also records "prefix", how many leading hash characters tell every
# image apart, so the page can show short names. Images arrive sorted by
# hash, so it is one more than the longest prefix neighbors share. Last
# comes "bytes", the images' total size, which buildWeb reports. The
# header also carries "accent", the page's WEBACCENT color.
# Globals:
#   SIL_LIBRARY, SIL_WEBACCENT, _silDateTag
# Arguments:
#   $1 - Epoch seconds to record as the build time
# Inputs:
#   webFacts records on STDIN
# Outputs:
#   JavaScript to STDOUT
#######################################
function webDataJs {
    ## The path goes through the environment, as awk -v would read
    ## backslashes in it as escapes. jsonEscape has already escaped it
    WEBSIL_LIBRARY="$(jsonEscape "$SIL_LIBRARY")" awk -F'\t' -v built="$1" \
        -v builtText="$(date -d "@$1" '+%Y-%m-%d %H:%M:%S')" -v dateTag="$_silDateTag" \
        -v accent="${SIL_WEBACCENT:-blue}" '
        ## webFacts has escaped tag paths; suffixes and dates need none
        function q(s) { return "\"" s "\"" }
        ## Counters start as "", not 0: the first tag would be numbered ""
        BEGIN { nTags = 0 }
        $1 == "D" { tagNum[$2] = nTags; tagList = tagList (nTags++ ? "," : "") q($2); next }
        $1 == "A" { aliasList = aliasList (nAlias++ ? "," : "") "[" q($2) "," q($3) "]"; next }
        $1 == "L" {
            dir = substr($2, 3)
            if (index(dir, dateTag "/") == 1) {
                if (match(dir, /[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]$/))
                    added[$3] = substr(dir, RSTART)
            } else if (dir in tagNum) {
                ## Test first: reading imgTags[$3] would create it
                sep = ($3 in imgTags) ? "," : ""
                imgTags[$3] = imgTags[$3] sep tagNum[dir]
            }
            next
        }
        ## Rows are written as they come, as building one string of them
        ## would slow to a crawl for a large library
        function start() {
            if (started++) return
            printf "/*\n * WebSIL data: every image in this library, with its size, date added\n"
            printf " * and tags, and the tag folders and LINK aliases, for WebSIL.html.\n"
            printf " * Each image is [hash, suffix, bytes, date added or null, [tag numbers]],\n"
            printf " * the numbers indexing the tags list. \"prefix\" is how many leading\n"
            printf " * hash characters tell every image apart; \"bytes\" is their total size.\n"
            printf " * \"accent\" is the page color, from WEBACCENT.\n *\n"
            printf " * Generated by sil BUILDWEB, which replaces it on each build: do not edit.\n */\n"
            printf "window.SIL_DATA = {\"version\":1,\"built\":%s,\"builtText\":%s,\"accent\":%s,", built, q(builtText), q(accent)
            printf "\"library\":%s,\n\"tags\":[%s],\n\"aliases\":[%s],\n", "\"" ENVIRON["WEBSIL_LIBRARY"] "\"", tagList, aliasList
            printf "\"images\":["
        }
        $1 == "I" {
            if ($2 !~ /^[0-9a-f]+\.[a-z0-9]+$/ || length($2) < 42) next
            start()
            dot = index($2, ".")
            hash = substr($2, 1, dot - 1)
            for (n = 0; n < length(hash) && substr(hash, n + 1, 1) == substr(prev, n + 1, 1); n++);
            if (n + 1 > prefix) prefix = n + 1
            prev = hash
            bytes += $3
            printf "%s[%s,%s,%s,%s,[%s]]", (nImages++ ? ",\n" : "\n"), q(hash), \
                q(substr($2, dot + 1)), $3, (($2 in added) ? q(added[$2]) : "null"), imgTags[$2]
        }
        ## Capped, as two files with one hash (eg x.jpg and x.png) never differ
        ## %.0f, as %d may cap at 2 GB in other awks
        END { start(); printf "],\n\"prefix\":%d,\"bytes\":%.0f};\n", (prefix > 40 ? 40 : prefix), bytes }'
}

#######################################
# Bring the library's .gitignore into line with GITWEB: without it, the
# page and its data are kept out of git, as each copy of a library builds
# its own. Tells the user what git needs when the setting changes.
# Globals:
#   SIL_LIBRARY, _silWebIgnores
# Outputs:
#   Notes on a change to STDERR
# Returns:
#   0 on success, 1 if .gitignore can't be written
#######################################
function webGitIgnore {
    local lib="$SIL_LIBRARY" ignore="$SIL_LIBRARY/.gitignore" line tmp
    local patterns=("${_silWebIgnores[@]/#/-e}")
    srcLib "replace"
    if [[ "$(webGitSetting)" == true ]]; then
        grep -qxF "${patterns[@]}" -- "$ignore" 2> /dev/null || return 0
        tmp="$(silMktemp)" || return 1
        ## grep fails when no lines remain, which is fine
        grep -vxF "${patterns[@]}" -- "$ignore" > "$tmp"
        placeLibraryFile "$tmp" "$ignore" || return 1
        msgInfo "GITWEB: web/ and WebSIL.html are no longer ignored by git. To share them:
    git -C '$lib' add web WebSIL.html"
        return 0
    fi
    local wasShared=0
    for line in "${_silWebIgnores[@]}"; do
        grep -qxF -- "$line" "$ignore" 2> /dev/null || wasShared=1
        ensureFileLine "$ignore" "$line" || return 1
    done
    if (( wasShared )) && git -C "$lib" ls-files --error-unmatch -- web WebSIL.html \
        > /dev/null 2>&1; then
        msgInfo "GITWEB off: web/ and WebSIL.html are now ignored by git, but committed
    copies stay in git until removed:
      git -C '$lib' rm -r --cached web WebSIL.html"
    fi
    return 0
}

#######################################
# Explain GITWEB given without BUILDWEB: the stamp has recorded it, but
# .gitignore waits for a build, and a library without a page has no stamp.
# Globals:
#   SIL_LIBRARY, SIL_GITWEB
# Outputs:
#   A note to STDERR
#######################################
function webGitNote {
    if [[ -d "$SIL_LIBRARY/web" ]]; then
        msgInfo "GITWEB recorded. The next BUILDWEB applies it to .gitignore:
    sil LIBRARY='$SIL_LIBRARY' BUILDWEB"
    else
        msgWarn "[!] GITWEB ignored: this library has no web page to share. Build one with it:
    sil LIBRARY='$SIL_LIBRARY' GITWEB=$(flagIsSet GITWEB && echo on || echo off) BUILDWEB"
    fi
}

#######################################
# Build the library's web page (BUILDWEB): copy WebSIL.html and its
# support files into place, write web/imageData.js from the library, and
# apply GITWEB to the library's .gitignore.
# Globals:
#   SIL_LIBRARY, myDir, _silWebFiles
# Outputs:
#   Progress, then the image count, total size and time taken, and the
#   page's location, to STDERR
# Returns:
#   0 on success, 1 if any file can't be written
#######################################
function buildWeb {
    local lib="$SIL_LIBRARY" name tmp built count bytes started
    started="$(clockMark)"
    msgInfo "BUILDWEB: building the library web page"
    mkdir -p -- "$lib/web" || return 1
    for name in "${!_silWebFiles[@]}"; do
        tmp="$(silMktemp)" || return 1
        cp -- "$myDir/templates/web/$name" "$tmp" \
            && placeLibraryFile "$tmp" "$lib/${_silWebFiles[$name]}" || return 1
    done
    webGitIgnore || return 1

    built="$(date +%s)"
    tmp="$(silMktemp)" || return 1
    if ! webFacts | webDataJs "$built" > "$tmp"; then
        rm -f -- "$tmp"
        msgWarn "[!] Could not write the web page data"
        return 1
    fi
    count="$(grep -c '^\["' -- "$tmp")"
    ## The total, from the data's last line, saves another pass over images/
    bytes="$(tail -n 1 -- "$tmp")"
    [[ "$bytes" =~ \"bytes\":([0-9]+) ]] && bytes="${BASH_REMATCH[1]}" || bytes=0
    placeLibraryFile "$tmp" "$lib/web/imageData.js" || return 1
    ## The build is the latest change: a clock read for the change time
    ## could tick past it, and make fresh data look out of date
    webStamp "$built" "$built" || return 1
    msgInfo "  $count images, $(humanSize "$bytes"), $(elapsedText "$started")
  Open in a web browser: $lib/WebSIL.html"
}
